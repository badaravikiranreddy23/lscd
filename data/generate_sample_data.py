def generate_sample_corpus(output_dir: str = "data/social_corpus") -> None:
    os.makedirs(output_dir, exist_ok=True)

    for word, periods in SAMPLE_DATA.items():
        word_dir = os.path.join(output_dir, word)
        os.makedirs(word_dir, exist_ok=True)

        for period_label, sentences in periods.items():
            txt_path = os.path.join(word_dir, f"{period_label}.txt")
            json_path = os.path.join(word_dir, f"{period_label}.json")

            with open(txt_path, "w", encoding="utf-8") as f:
                for s in sentences:
                    f.write(s + "\n")

            with open(json_path, "w", encoding="utf-8") as f:
                json.dump({
                    "word": word,
                    "period": period_label,
                    "sentences": sentences
                }, f, indent=2)

        print(f"✅ Generated sample data for '{word}'")

    print(f"\n📁 Sample corpus saved to: {output_dir}")
    print(f"Words available: {list(SAMPLE_DATA.keys())}")


if __name__ == "__main__":
    generate_sample_corpus()
